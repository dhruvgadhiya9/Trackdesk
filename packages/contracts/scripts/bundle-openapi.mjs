#!/usr/bin/env node
// Merges packages/contracts/openapi/*.yaml (one file per module) into one OpenAPI 3.1 document:
// packages/contracts/generated/openapi.bundled.yaml. Fails on duplicate paths, schemas,
// operationIds, or on operations missing x-roles / x-permission.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const specDir = join(root, 'openapi');
const outFile = join(root, 'generated', 'openapi.bundled.yaml');
const METHODS = ['get', 'put', 'post', 'delete', 'patch'];

const doc = YAML.parse(readFileSync(join(specDir, '_root.yaml'), 'utf8'));
doc.paths = {};
doc.tags = [];
const errors = [];
const operationIds = new Map();

const files = readdirSync(specDir)
  .filter((f) => f.endsWith('.yaml') && f !== '_root.yaml')
  .sort();

for (const file of files) {
  const part = YAML.parse(readFileSync(join(specDir, file), 'utf8')) ?? {};
  for (const tag of part.tags ?? []) doc.tags.push(tag);
  for (const [path, item] of Object.entries(part.paths ?? {})) {
    if (doc.paths[path]) errors.push(`${file}: duplicate path ${path}`);
    doc.paths[path] = item;
    for (const m of METHODS) {
      const op = item[m];
      if (!op) continue;
      const where = `${file}: ${m.toUpperCase()} ${path}`;
      if (!op.operationId) errors.push(`${where} has no operationId`);
      else if (operationIds.has(op.operationId))
        errors.push(`${where}: duplicate operationId ${op.operationId} (also in ${operationIds.get(op.operationId)})`);
      else operationIds.set(op.operationId, file);
      if (!op['x-roles']) errors.push(`${where} is missing x-roles`);
      if (!op['x-permission']) errors.push(`${where} is missing x-permission`);
    }
  }
  for (const [section, entries] of Object.entries(part.components ?? {})) {
    doc.components[section] ??= {};
    for (const [name, value] of Object.entries(entries)) {
      if (doc.components[section][name]) errors.push(`${file}: duplicate components.${section}.${name}`);
      doc.components[section][name] = value;
    }
  }
}

// Every local $ref must resolve.
const refs = new Set();
(function walk(node) {
  if (Array.isArray(node)) node.forEach(walk);
  else if (node && typeof node === 'object') {
    if (typeof node.$ref === 'string') refs.add(node.$ref);
    Object.values(node).forEach(walk);
  }
})(doc);
for (const ref of refs) {
  const [, section, name] = ref.match(/^#\/components\/([^/]+)\/(.+)$/) ?? [];
  if (!section || !doc.components[section]?.[name]) errors.push(`unresolved $ref ${ref}`);
}

if (errors.length) {
  console.error('OpenAPI bundle failed:\n  ' + errors.join('\n  '));
  process.exit(1);
}

mkdirSync(dirname(outFile), { recursive: true });
const header = '# GENERATED by packages/contracts/scripts/bundle-openapi.mjs — DO NOT EDIT.\n';
writeFileSync(outFile, header + YAML.stringify(doc, { lineWidth: 0, aliasDuplicateObjects: false }));
console.log(`Bundled ${files.length} module specs, ${operationIds.size} operations -> ${outFile}`);
